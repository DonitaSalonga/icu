-- M3 screenshots: table, event link, private Storage bucket and its policies.
-- Design: docs/SDD.md § Data model (screenshots), § Direct table access under RLS (storage.objects).
-- Requirements: R16, R21, R25. Path layout: {session_id}/{attempt_id}/{screenshot_id}.jpg

create table public.screenshots (
  id uuid primary key, -- generated by the client so retried uploads can't duplicate (R30)
  attempt_id uuid not null references public.attempts (id) on delete cascade,
  storage_path text not null unique,
  captured_at timestamptz not null,
  reason text not null check (reason in ('interval', 'violation')),
  bytes int not null check (bytes > 0 and bytes <= 512000),
  received_at timestamptz not null default now()
);
create index screenshots_attempt_captured_idx on public.screenshots (attempt_id, captured_at);

create trigger screenshots_set_received_at
  before insert on public.screenshots
  for each row execute function public.set_received_at();

alter table public.events
  add constraint events_screenshot_id_fkey
  foreign key (screenshot_id) references public.screenshots (id) on delete set null;

alter table public.screenshots enable row level security;

create policy screenshots_student_insert on public.screenshots
  for insert to authenticated
  with check (private.can_write_attempt(attempt_id, captured_at));

create policy screenshots_admin_select on public.screenshots
  for select to authenticated
  using (private.is_attempt_admin(attempt_id));

-- ---------------------------------------------------------------------------
-- Storage
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('screenshots', 'screenshots', false, 512000, array['image/jpeg'])
on conflict (id) do nothing;

-- The attempt id from a screenshot object path, or null if the path doesn't have the expected shape.
create function private.screenshot_path_ids(p_name text, out session_id uuid, out attempt_id uuid)
language plpgsql
immutable
set search_path = ''
as $$
declare
  parts text[] := string_to_array(p_name, '/');
  uuid_re constant text := '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$';
begin
  if cardinality(parts) = 3 and parts[1] ~ uuid_re and parts[2] ~ uuid_re and parts[3] ~ ('^[0-9a-f-]{36}\.jpg$') then
    session_id := parts[1]::uuid;
    attempt_id := parts[2]::uuid;
  end if;
end;
$$;

-- R16, R25: a student uploads only into their own attempt's folder, while they could also write events.
create function private.can_upload_screenshot(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from private.screenshot_path_ids(p_name) ids
    join public.attempts a on a.id = ids.attempt_id and a.session_id = ids.session_id
    where private.can_write_attempt(a.id, now())
  );
$$;

-- R21, R23: the session's admin can read (signed URLs) and delete its screenshots.
create function private.can_admin_screenshot(p_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from private.screenshot_path_ids(p_name) ids
    where ids.session_id is not null and private.is_session_admin(ids.session_id)
  );
$$;

create policy screenshots_student_upload on storage.objects
  for insert to authenticated
  with check (bucket_id = 'screenshots' and private.can_upload_screenshot(name));

create policy screenshots_admin_read on storage.objects
  for select to authenticated
  using (bucket_id = 'screenshots' and private.can_admin_screenshot(name));

create policy screenshots_admin_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'screenshots' and private.can_admin_screenshot(name));

revoke execute on function
  private.screenshot_path_ids(text),
  private.can_upload_screenshot(text),
  private.can_admin_screenshot(text)
from public, anon;

grant execute on function
  private.screenshot_path_ids(text),
  private.can_upload_screenshot(text),
  private.can_admin_screenshot(text)
to authenticated;
