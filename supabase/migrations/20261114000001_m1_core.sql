-- R2: profile created from sign-up metadata; the role is fixed at sign-up.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role text := new.raw_user_meta_data ->> 'role';
  v_name text := btrim(coalesce(new.raw_user_meta_data ->> 'full_name', ''));
begin
  if v_role is null or v_role not in ('student', 'admin') then
    raise exception 'OCM_INVALID_ROLE';
  end if;
  if v_name = '' or char_length(v_name) > 120 then
    raise exception 'OCM_INVALID_INPUT';
  end if;
  insert into public.profiles (id, role, full_name, email)
  values (new.id, v_role, v_name, coalesce(new.email, ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- R14: gaps use server time only; client-supplied received_at is overwritten.
create function public.set_received_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.received_at := now();
  return new;
end;
$$;

create trigger events_set_received_at
  before insert on public.events
  for each row execute function public.set_received_at();

create trigger heartbeats_set_received_at
  before insert on public.heartbeats
  for each row execute function public.set_received_at();

