-- M1 core schema: profiles, exam sessions, attempts, events, heartbeats.
-- Design: docs/SDD.md § Data model, § Interfaces and APIs. Requirements: docs/PRD.md R2, R4, R6–R8, R10, R14, R25.
-- Applied to Supabase Cloud with `npx supabase db push --linked` (no local stack, IDEA.md Q19).
-- RPC errors are raised as messages starting with OCM_ so clients can map them to UI text.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('student', 'admin')),
  full_name text not null check (char_length(full_name) between 1 and 120),
  email text not null,
  created_at timestamptz not null default now()
);

create table public.exam_sessions (
  id uuid primary key default gen_random_uuid(),
  admin_id uuid not null references public.profiles (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  -- Alphabet must match packages/core SESSION_CODE_ALPHABET (checked by packages/core/test/sql-parity.test.ts).
  code text not null unique check (code ~ '^[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{6}$'),
  url_patterns text[] not null check (cardinality(url_patterns) between 1 and 10),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  warning_limit int not null default 3 check (warning_limit between 1 and 10),
  threshold_medium int not null default 10,
  threshold_high int not null default 25,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at),
  check (threshold_medium > 0 and threshold_medium < threshold_high)
);
create index exam_sessions_admin_id_idx on public.exam_sessions (admin_id);

create table public.attempts (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.exam_sessions (id) on delete cascade,
  student_id uuid not null references public.profiles (id) on delete cascade,
  status text not null default 'joined' check (status in ('joined', 'active', 'ended')),
  consent_at timestamptz,
  consent_version text,
  age_confirmed boolean not null default false,
  started_at timestamptz,
  ended_at timestamptz,
  end_reason text check (end_reason in ('student', 'time_window')),
  uninstall_token uuid unique,
  verdict text check (verdict in ('cleared', 'suspicious', 'cheating_confirmed')),
  verdict_note text check (char_length(verdict_note) <= 1000),
  verdict_by uuid references public.profiles (id),
  verdict_at timestamptz,
  data_deleted_at timestamptz,
  created_at timestamptz not null default now(),
  unique (session_id, student_id)
);
create index attempts_session_id_idx on public.attempts (session_id);
-- R8: at most one active attempt per student.
create unique index attempts_one_active_per_student on public.attempts (student_id) where status = 'active';

create table public.events (
  id uuid primary key, -- generated by the client so retried uploads are idempotent (R30)
  attempt_id uuid not null references public.attempts (id) on delete cascade,
  -- Must match packages/core EVENT_TYPES (checked by packages/core/test/sql-parity.test.ts).
  type text not null check (type in (
    'exam_tab_hidden',
    'exam_tab_visible',
    'window_blur',
    'window_focus',
    'navigated_off_exam',
    'tab_opened',
    'url_visited',
    'copy',
    'cut',
    'paste',
    'context_menu',
    'fullscreen_enter',
    'fullscreen_exit',
    'exam_page_not_detected',
    'warning_shown',
    'warning_limit_reached',
    'screenshot_failed',
    'extension_uninstalled',
    'queue_overflow'
  )),
  occurred_at timestamptz not null,
  received_at timestamptz not null default now(),
  details jsonb not null default '{}'::jsonb check (pg_column_size(details) <= 2048),
  screenshot_id uuid -- FK to screenshots added in M3
);
create index events_attempt_occurred_idx on public.events (attempt_id, occurred_at);

create table public.heartbeats (
  id bigint generated always as identity primary key,
  attempt_id uuid not null references public.attempts (id) on delete cascade,
  received_at timestamptz not null default now(),
  source text not null default 'content' check (source in ('content', 'alarm'))
);
create index heartbeats_attempt_received_idx on public.heartbeats (attempt_id, received_at);

