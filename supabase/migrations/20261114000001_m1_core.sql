create function public.current_role_is(p_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = p_role);
$$;

create function public.is_session_admin(p_session_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.exam_sessions where id = p_session_id and admin_id = auth.uid());
$$;

create function public.is_attempt_admin(p_attempt_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.attempts a
    join public.exam_sessions s on s.id = a.session_id
    where a.id = p_attempt_id and s.admin_id = auth.uid()
  );
$$;

-- Admins may read the profiles of students who joined one of their sessions.
create function public.is_student_in_my_sessions(p_student_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.attempts a
    join public.exam_sessions s on s.id = a.session_id
    where a.student_id = p_student_id and s.admin_id = auth.uid()
  );
$$;

-- R8, R25, R30: students write events only for their own started attempt, while it is active
-- or within 1 hour after it ended (offline queue grace), and only for times inside the attempt
-- window (2 minutes of tolerance; the extension corrects its clock to server time).
create function public.can_write_attempt(p_attempt_id uuid, p_occurred_at timestamptz)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.attempts a
    join public.exam_sessions s on s.id = a.session_id
    where a.id = p_attempt_id
      and a.student_id = auth.uid()
      and a.started_at is not null
      and (a.status = 'active' or (a.status = 'ended' and now() < a.ended_at + interval '1 hour'))
      and p_occurred_at >= a.started_at - interval '2 minutes'
      and p_occurred_at <= coalesce(a.ended_at, s.ends_at) + interval '2 minutes'
  );
$$;

-- R14: heartbeats only while the attempt is active and the session window is open.
create function public.can_heartbeat(p_attempt_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.attempts a
    join public.exam_sessions s on s.id = a.session_id
    where a.id = p_attempt_id
      and a.student_id = auth.uid()
      and a.status = 'active'
      and now() <= s.ends_at
  );
$$;

